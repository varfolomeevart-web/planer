#!/bin/bash
# Создание GitHub Release v1.5 через API
set -e
cd /home/z/my-project
export $(grep GITHUB_TOKEN .env | xargs)

cat > /tmp/release-body.json << 'EOF'
{
  "tag_name": "v1.5",
  "name": "v1.5 — Бриф для 3D-визуализатора: материалы, освещение, ракурсы",
  "body": "## Новое в v1.5\n\nТекстовое ТЗ для 3D-визуализатора доведено до полного брифа:\n\n### МАТЕРИАЛЫ И ТЕКСТУРЫ\n- HEX-пипетка у всех материалов (этаж: пол/стены/потолок; объект: корпус) — цвет попадает в ТЗ в формате «HEX: #505050»\n- Уточнения: размер плитки (60×60), высота фартука («плитка-кабанчик до 160 см»), столешница/фасад барной стойки\n- Оборудование в ТЗ группируется по материалу («нержавеющая сталь матовая — HICOLD, POLAIR…»)\n- Лестница: отдельной строкой ступени и перила\n- Цены каталога «Клён» автоматически срезаются из названий\n\n### ОСВЕЩЕНИЕ\n- Новое поле «Освещение по зонам» (по строке на зону) + чипы-подсказки (LED-панели, подвесные лофт, трековые, LED-лента, диммер)\n\n### РАКУРСЫ\n- Приоритетные точки обзора с уточнениями (высота камеры, что в кадре) + чипы: «Изометрия сверху», «Вид от входа», «Вид из кухни на лестницу», «Вид вдоль барной стойки»\n\n### Прочее\n- Дефолт «нержавеющая сталь матовая» для всего оборудования «Клён» (HICOLD, POLAIR, Hurakan, Indokor, Luxstahl) и типовых приборов\n- Кнопка «ТЗ» в тулбаре: бриф копируется в буфер одним кликом (fallback — скачивание .txt)\n- Совместимо со старыми сохранениями (новые поля аддитивны, миграция не требуется)\n\n**Live:** https://room-planner-ru.surge.sh"
}
EOF

curl -s -X POST \
  -H "Authorization: Bearer ${GITHUB_TOKEN}" \
  -H "Accept: application/vnd.github+json" \
  https://api.github.com/repos/varfolomeevart-web/planer/releases \
  -d @/tmp/release-body.json | grep -E '"html_url"|"tag_name"' | head -3
